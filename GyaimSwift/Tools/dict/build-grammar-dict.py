#!/usr/bin/env python3
"""Generate Resources/grammar-dict.txt: the hiragana tails that follow a predicate (ADR-042).

One conversion covers one content word plus whatever follows it in hiragana:
auxiliaries, particles, auxiliary verbs (ている / てみる / てもらう ...) and formal
nouns (こと / とき / ため / はず ...). The Gictionary-derived dict.txt composes
conjugations but its tail grammar is patchy (the te-form of 使う / 取る / 待つ
does not reach てみる, nothing follows 終止形 + けど / こと / べき, 形容詞 + です
is missing ...). This file fills those holes with our own rows, kept apart
from dict.txt so that replacing dict.txt with a newer Gictionary keeps them.
The class numbers below are those of the bundled dict.txt; if a new dict.txt
renumbers them, GrammarCoverageTests fails and the numbers here need fixing.
An imported ~/.gyaim/connectiondict.txt disables this file (Config).

The spec is the matrix in Tests/GyaimTests/GrammarCoverageMatrix.swift;
GrammarCoverageTests checks that every cell composes.

Connection classes used here:
    existing (dict.txt)  2 / 16 / 23 / 87 / 123  godan endings with 促音便 (って / った)
                         6 一段, 51 サ変, 52 / 73 / 74 after られ / させ, 19 形容動詞,
                         40 形容詞, 54 ない and たい, 35 連用形の後ろ, 41 終止連体形の後ろ,
                         72 after ま(す), 92 after 意向形 / です, 162 after そう
    ours                 224 連用形 + なる (ADR-041), 230 て形の後ろ,
                         231 形式名詞・べき の後ろ, 232 仮定形 ば の後ろ

Rows only match when the whole reading is typed, so a wrong but grammatical-
looking form (静かならしい) costs nothing unless someone types exactly that.

Usage:
    python3 Tools/dict/build-grammar-dict.py            # rewrite Resources/grammar-dict.txt
    python3 Tools/dict/build-grammar-dict.py --check    # exit 1 when the file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[2] / "Resources/grammar-dict.txt"
NARU, TE, NOM, BA = 224, 230, 231, 232
NAMED = {"": 0, "TE": TE, "NOM": NOM, "BA": BA}

lines: list[str] = []


def section(title: str) -> None:
    lines.append(f"# {title}")


def row(kana: str, surface: str, in_class: int, out_class: int = 0) -> None:
    lines.append(f"{kana}\t{surface}\t{in_class}\t{out_class or ''}")


def tails(in_class: int, spec: str) -> None:
    """`かな` ends the conversion, `かな>N` continues into class N. The surface is `*かな`."""
    for item in spec.split():
        kana, _, out = item.partition(">")
        row(kana, f"*{kana}", in_class, NAMED[out] if out in NAMED else int(out))


def build() -> str:
    lines.clear()
    lines.append("# Generated by Tools/dict/build-grammar-dict.py (ADR-042). Do not edit by hand.")
    # ConnectionDict emits compositions through a tail grammar after the dictionary-only results.
    lines.append("# @tail")

    section("て形から 230 へ: 既存の て / で と同じ読みの行を足す")
    for in_class, kana in [(2, "って"), (16, "って"), (23, "って"), (87, "って"), (123, "って"), (6, "て"), (30, "じて"),
                           (31, "て"), (33, "て"), (52, "て"), (74, "て"), (193, "で"), (194, "で")]:
        row(kana, f"*{kana}", in_class, TE)
    row("して", "して", 51, TE)

    section("促音便の った から 終止連体形の後ろ (41) と たら (134) へ")
    for in_class in (2, 16, 23, 87, 123):
        row("った", "*った", in_class, 41)
        row("った", "*った", in_class, 134)

    section("230: て形の後ろ（補助用言と助詞）")
    tails(TE, "る>41 ます ました ません た>41 たら て>TE も は から ばかり こそ さえ もいい>41 もいいです もよい>41 もかまわない")
    tails(TE, "いる>41 います いました いた>41 いて>TE いない いなかった いれば")
    tails(TE, "ある>41 あります あった>41 あって おく>41 おきます おきました おいた>41 おいて>TE おこう おけば")
    tails(TE, "みる>41 みます みました みた>41 みて>TE みよう みたい みれば みない")
    tails(TE, "しまう>41 しまいます しまいました しまった>41 しまって>TE しまえば")
    tails(TE, "くる>41 きます きました きた>41 きて>TE こない いく>41 いきます いきました いった>41 いって>TE いかない いけば いこう")
    tails(TE, "もらう>41 もらいます もらいました もらった>41 もらって>TE もらえる>41 もらえます もらえない もらいたい")
    tails(TE, "くれる>41 くれます くれました くれた>41 くれて>TE くれない あげる>41 あげます あげた>41 あげて>TE")
    tails(TE, "ほしい>41 ほしかった>41 ほしくない ほしいです ください くださる>41 くださった>41 くださって")
    tails(TE, "いただく>41 いただきます いただきました いただいた>41 いただいて>TE いただける>41 いただけます いただき")
    tails(TE, "おります おりました おり")
    row("な", "*な*", TE, 54)  # てない / てなかった / てなくて

    section("41: 終止形・連体形・た形の後ろ")
    tails(41, "べき>NOM けど けれど けれども し ね よね な なあ かな かどうか>NOM かもしれません と なら ならば という>41 といった とか って")
    tails(41, "はず>NOM こと>NOM もの>NOM ものの ところ>NOM とき>NOM ため>NOM の>NOM のに のか のだ")
    tails(41, "ことがある>41 ことができる>41 ことになる>41 ことにする>41 こともある>41 ことはない>41 わけではない")
    tails(41, "ような ようです ようになる>41 ようになった>41 ようになります ようにする>41 ようにした>41 ようにして>TE ようにします")
    tails(41, "そうだ そうです まで>NOM までに みたい>NOM つもり>NOM わけ>NOM だけ>NOM ほど>NOM")
    tails(41, "ほう>NOM ほうがいい>41 ばかり>NOM あと>NOM まま>NOM")

    section("231: 形式名詞・べき の後ろ（助詞と断定）")
    tails(NOM, "が を に で は も と の へ や から まで より には では とは にも でも だけ か かも かな")
    tails(NOM, "だ です だった でした ではない じゃない ではありません なら なので なのに だから だろう でしょう である")
    tails(NOM, "ですが ですね ですよ ですか だと だが だし として について によって")
    tails(NOM, "になる>41 になった>41 にする>41 にした>41 がある>41 がない はない もある>41")

    section("仮定形 ば から 232 へ: 既存の ば と同じ読みの行を足す")
    for in_class, kana in [(2, "えば"), (123, "えば"), (43, "けば"), (87, "けば"), (28, "げば"), (26, "せば"), (23, "てば"),
                           (137, "ねば"), (46, "べば"), (8, "めば"), (16, "れば"), (52, "れば"), (73, "れば"), (6, "れば"),
                           (74, "れば"), (30, "ずれば"), (144, "せれば"), (40, "ければ"), (54, "ければ")]:
        row(kana, f"*{kana}", in_class, BA)
    for in_class, kana, surface in [(51, "すれば", "すれば"), (84, "いれば", "いれば"), (86, "くれば", "来れば"), (86, "くれば", "くれば")]:
        row(kana, surface, in_class, BA)
    row("れば", "*れば", 74)  # dict.txt only has the non-terminal *れば*
    tails(BA, "いい>41 いいです いいですか いいのか よい>41 よかった>41 よかったです")

    section("92: 意向形・ます・です の後ろの終助詞")
    tails(92, "か かな よ よね")

    section("連用形 + やすい / にくい / づらい: 35 から形容詞語尾 (40) へ。dict.txt の出力先 83 は空")
    for kana in ("やす", "にく", "づら"):
        row(kana, f"*{kana}*", 35, 40)

    section("72: ま(す) の後ろ")
    tails(72, "すので すから すか すね すよ すけど すし せんでした せんか したら したが したので")

    section("162: そう の後ろ")
    tails(162, "です でした")

    section("形容詞 (40) と ない / たい (54)")
    for in_class in (40, 54):
        tails(in_class, "いです いですが いですね いですよ いですか いですし かったです かったら かったり さそう くても くは くも")
    tails(40, "い>41 かった>41 さ そう そうだ そうです そうな そうに")
    row("すぎ", "*すぎ*", 40, 6)  # すぎる / すぎた / すぎて
    row("く", "*く*", 40, 36)  # くない / くなかった / くなくて
    row("く", "*く*", 40, 51)  # くする / くして / くします
    row("く", "*く*", 54, 51)

    section("形容動詞 (19)")
    tails(19, "だった>41 だったら でしたが ではない じゃない ではありません なら なので なのに だから だろう だと だが だし だね だよ")
    tails(19, "ですが ですね ですよ ですか である かも かもしれない そう そうだ")
    row("な", "*な*", 19, 41)  # なこと / なので / なはず
    row("に", "*に*", 19, 51)  # にする / にして

    section("一段 (6) と サ変 (51)")
    tails(6, "ず ずに れば")
    row("させ", "*させ*", 6, 52)  # させた / させます
    row("せず", "せず", 51)
    row("せずに", "せずに", 51)

    section("連用形 + なる (ADR-041): 224 を経て な の五段活用 (16) へ")
    row("く", "*く", 40, NARU)
    row("に", "*に", 19, NARU)
    row("く", "*く", 54, NARU)
    row("な", "*な*", NARU, 16)

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail when the file differs from the generated rows")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
            print(f"{args.output} is stale: run Tools/dict/build-grammar-dict.py", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"{args.output}: {sum(1 for line in text.splitlines() if not line.startswith('#'))} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
